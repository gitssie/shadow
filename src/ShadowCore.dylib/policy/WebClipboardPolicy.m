#import "FingerprintPolicy.h"

NSString *SHDWFingerprintWebClipboardScript(void) {
    return
        @"(() => {\n"
        @"  const anchor = typeof EventTarget === 'function' ? EventTarget.prototype : null;\n"
        @"  const key = Symbol.for('Shadow.WebClipboard.installed');\n"
        @"  if (anchor) {\n"
        @"    let realms = anchor[key];\n"
        @"    if (!realms) {\n"
        @"      realms = new WeakSet();\n"
        @"      try { Object.defineProperty(anchor, key, { value: realms }); } catch (_) {}\n"
        @"    }\n"
        @"    if (realms.has(globalThis)) return;\n"
        @"    realms.add(globalThis);\n"
        @"  }\n"
        @"  let clipboard;\n"
        @"  try { clipboard = typeof navigator === 'object' ? navigator.clipboard : null; } catch (_) {}\n"
        @"  let clipboardGetter;\n"
        @"  for (let owner = typeof navigator === 'object' ? navigator : null; owner; owner = Object.getPrototypeOf(owner)) {\n"
        @"    const descriptor = Object.getOwnPropertyDescriptor(owner, 'clipboard');\n"
        @"    if (descriptor && typeof descriptor.get === 'function') { clipboardGetter = descriptor.get; break; }\n"
        @"  }\n"
        @"  const isClipboard = receiver => {\n"
        @"    if (receiver === clipboard) return true;\n"
        @"    if (!clipboardGetter || !receiver) return false;\n"
        @"    const pending = [globalThis];\n"
        @"    const visited = new Set();\n"
        @"    while (pending.length) {\n"
        @"      const realm = pending.pop();\n"
        @"      if (!realm || visited.has(realm)) continue;\n"
        @"      visited.add(realm);\n"
        @"      try {\n"
        @"        if (clipboardGetter.call(realm.navigator) === receiver) return true;\n"
        @"        pending.push(realm.parent, realm.opener);\n"
        @"        for (let index = 0; index < realm.frames.length; index++) pending.push(realm.frames[index]);\n"
        @"      } catch (_) {}\n"
        @"    }\n"
        @"    return false;\n"
        @"  };\n"
        @"  if (clipboard) {\n"
        @"    for (const name of ['readText', 'read']) {\n"
        @"      if (typeof clipboard[name] !== 'function') continue;\n"
        @"      const emptyRead = function () {\n"
        @"        if (!isClipboard(this)) throw new TypeError('Illegal invocation');\n"
        @"        return Promise.resolve(name === 'readText' ? '' : []);\n"
        @"      };\n"
        @"      for (let owner = clipboard; owner && owner !== Object.prototype; owner = Object.getPrototypeOf(owner)) {\n"
        @"        const descriptor = Object.getOwnPropertyDescriptor(owner, name);\n"
        @"        if (!descriptor) continue;\n"
        @"        try {\n"
        @"          Object.defineProperty(owner, name, { configurable: descriptor.configurable,\n"
        @"            enumerable: descriptor.enumerable, writable: 'writable' in descriptor ? descriptor.writable : true,\n"
        @"            value: emptyRead });\n"
        @"        } catch (_) {}\n"
        @"      }\n"
        @"    }\n"
        @"  }\n"
        @"  const typeDescriptor = typeof Event === 'function'\n"
        @"    ? Object.getOwnPropertyDescriptor(Event.prototype, 'type') : null;\n"
        @"  const eventTypeGetter = typeDescriptor && typeDescriptor.get;\n"
        @"  const inputPrototype = typeof InputEvent === 'function' ? InputEvent.prototype : null;\n"
        @"  const inputDescriptor = inputPrototype\n"
        @"    ? Object.getOwnPropertyDescriptor(inputPrototype, 'inputType') : null;\n"
        @"  const inputTypeGetter = inputDescriptor && inputDescriptor.get;\n"
        @"  const eventType = event => eventTypeGetter ? eventTypeGetter.call(event) : event.type;\n"
        @"  const inputType = event => inputTypeGetter ? inputTypeGetter.call(event) : event.inputType;\n"
        @"  const transfers = new WeakMap();\n"
        @"  const emptyTransfer = event => {\n"
        @"    if (transfers.has(event)) return transfers.get(event);\n"
        @"    let transfer;\n"
        @"    try { if (typeof DataTransfer === 'function') transfer = new DataTransfer(); } catch (_) {}\n"
        @"    if (!transfer) {\n"
        @"      const empty = Object.freeze([]);\n"
        @"      transfer = Object.freeze({ getData: () => '', types: empty, items: empty, files: empty });\n"
        @"    }\n"
        @"    transfers.set(event, transfer);\n"
        @"    return transfer;\n"
        @"  };\n"
        @"  const isPasteInput = event => (eventType(event) === 'beforeinput' || eventType(event) === 'input') &&\n"
        @"    (inputType(event) === 'insertFromPaste' || inputType(event) === 'insertFromPasteAsQuotation');\n"
        @"  const replaceGetter = (prototype, name, select, value) => {\n"
        @"    if (!prototype) return;\n"
        @"    const descriptor = Object.getOwnPropertyDescriptor(prototype, name);\n"
        @"    if (!descriptor || typeof descriptor.get !== 'function' || !descriptor.configurable) return;\n"
        @"    try {\n"
        @"      Object.defineProperty(prototype, name, { configurable: descriptor.configurable,\n"
        @"        enumerable: descriptor.enumerable, get: function () {\n"
        @"        const original = descriptor.get.call(this);\n"
        @"        return select(this) ? value(this) : original;\n"
        @"      } });\n"
        @"    } catch (_) {}\n"
        @"  };\n"
        @"  replaceGetter(typeof ClipboardEvent === 'function' ? ClipboardEvent.prototype : null,\n"
        @"    'clipboardData', event => eventType(event) === 'paste', emptyTransfer);\n"
        @"  replaceGetter(inputPrototype, 'data', isPasteInput, () => null);\n"
        @"  replaceGetter(inputPrototype, 'dataTransfer', isPasteInput, emptyTransfer);\n"
        @"  const mask = (event, name, value) => {\n"
        @"    if (!(name in event)) return;\n"
        @"    try { Object.defineProperty(event, name, { configurable: true, get: () => value }); } catch (_) {}\n"
        @"  };\n"
        @"  if (typeof addEventListener === 'function') {\n"
        @"    addEventListener('paste', event => {\n"
        @"      event.preventDefault();\n"
        @"      mask(event, 'clipboardData', emptyTransfer(event));\n"
        @"    }, true);\n"
        @"    addEventListener('beforeinput', event => {\n"
        @"      if (!isPasteInput(event)) return;\n"
        @"      event.preventDefault();\n"
        @"      mask(event, 'data', null);\n"
        @"      mask(event, 'dataTransfer', emptyTransfer(event));\n"
        @"    }, true);\n"
        @"  }\n"
        @"})();\n"
        ;
}
